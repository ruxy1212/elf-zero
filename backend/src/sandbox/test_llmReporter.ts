import * as fs from "fs";
import * as path from "path";
import { PublicKey } from "@solana/web3.js";
import { InvariantEngine } from "./invariantEngine";
import { LlmReporter } from "./llmReporter";

async function runTests() {
  console.log("=== ElfZero: Substep 4.3 LLM Security Reporter Verification ===");

  const programId = new PublicKey("D8r3d2uXQn9wYE96BRjyYqmqReFbziK5rfSwdYvHEtkT");
  const payloadsDir = path.resolve(__dirname, "../../../payloads");
  const engine = new InvariantEngine(programId);
  const reporter = new LlmReporter();

  // Test 1: Generate Advisory for Safe Baseline (vault_v1_clean.so)
  console.log("\n[Test 1] Generating Security Advisory for Clean V1 Payload:");
  const cleanElf = fs.readFileSync(path.join(payloadsDir, "vault_v1_clean.so"));
  const reportV1 = await engine.evaluateCandidateBytecode(cleanElf, "e0f8a3a24acc56c3e316ca073e26db0c90ba09a5fa193b1c917a52fb1b49db50");
  const advisoryV1 = await reporter.generateAdvisory(reportV1);

  console.log(`  Title: ${advisoryV1.title}`);
  console.log(`  Verdict: ${advisoryV1.verdict}`);
  console.log(`  Risk Score: ${advisoryV1.riskScore}/100`);
  console.log(`  Generated By: ${advisoryV1.generatedBy}`);
  console.log(`  Action: ${advisoryV1.recommendedAction}`);

  if (advisoryV1.verdict !== "SAFE" || advisoryV1.riskScore > 10) {
    throw new Error(`Expected clean V1 advisory to be SAFE with risk score <= 10, got ${advisoryV1.riskScore}`);
  }

  // Test 2: Generate Advisory for Exploit Upgrade (vault_v2_malicious.so)
  console.log("\n[Test 2] Generating Security Advisory for Malicious V2 Exploit:");
  const maliciousElf = fs.readFileSync(path.join(payloadsDir, "vault_v2_malicious.so"));
  const reportV2 = await engine.evaluateCandidateBytecode(maliciousElf, "46299c59b06a12fc9d617976cf8d256ac9029220c4c4ef5353247b32d49f461f");
  const advisoryV2 = await reporter.generateAdvisory(reportV2);

  console.log(`  Title: ${advisoryV2.title}`);
  console.log(`  Verdict: ${advisoryV2.verdict}`);
  console.log(`  Risk Score: ${advisoryV2.riskScore}/100`);
  console.log(`  Generated By: ${advisoryV2.generatedBy}`);
  console.log(`  Action: ${advisoryV2.recommendedAction}`);

  if (advisoryV2.verdict !== "MALICIOUS_BACKDOOR_DETECTED" || advisoryV2.riskScore < 80) {
    throw new Error(`Expected malicious V2 advisory to have high risk score >= 80, got ${advisoryV2.riskScore}`);
  }

  console.log("\n--- Preview of Generated Markdown Advisory (V2 Malicious) ---");
  console.log(advisoryV2.rawMarkdown);

  // Test 3: Deterministic Fallback Engine
  console.log("\n[Test 3] Testing Deterministic Fallback Engine directly:");
  const fallbackAdvisory = reporter.generateDeterministicAdvisory(reportV2);
  console.log(`  Fallback Title: ${fallbackAdvisory.title}`);
  console.log(`  Fallback Risk Score: ${fallbackAdvisory.riskScore}/100`);
  console.log(`  Fallback Engine: ${fallbackAdvisory.generatedBy}`);

  if (fallbackAdvisory.riskScore < 80) {
    throw new Error("Fallback advisory must reflect high risk for exploit report");
  }

  console.log("\n>>> ALL SUBSTEP 4.3 LLM REPORTER TESTS PASSED! <<<\n");
}

runTests().catch((err) => {
  console.error("Test failed with error:", err);
  process.exit(1);
});
